"""Conversion of browser cookies (sent by the extension) to a Netscape cookie file.

The file is what yt-dlp's --cookies option expects. It carries a live session, so
three things matter and are enforced here:

1. Mode 0600, inside a private 0700 directory — never in `downloads/`, which is a
   folder the user opens, syncs and shares.
2. Deleted as soon as the job that uses it finishes.
3. Swept at startup, because point 2 lives in a `finally` and a SIGKILL (or closing
   the terminal window) never runs it.
"""

import getpass
import os
import tempfile
from pathlib import Path
from typing import Iterable, Mapping

COOKIE_FILE_GLOB = "cookies-*.txt"


def cookie_dir() -> str:
    """Private directory (0700) for the temporary cookie jars.

    A fixed name under the system temp is convenient for sweeping orphans across
    restarts, but on a shared machine `/tmp` is hostile: another user could get
    there first. So the name carries the username and we refuse anything we do
    not own, or any symlink pointing elsewhere.
    """
    path = Path(tempfile.gettempdir()) / f"video-dl-cookies-{getpass.getuser()}"

    if path.is_symlink():
        raise RuntimeError(f"{path} es un symlink; no se escriben credenciales ahí")

    path.mkdir(mode=0o700, exist_ok=True)

    st = path.stat()
    if hasattr(os, "getuid") and st.st_uid != os.getuid():
        raise RuntimeError(f"{path} no pertenece a este usuario; abortando")

    # Puede haber existido de antes con permisos laxos.
    os.chmod(path, 0o700)
    return str(path)


def write_netscape_cookiefile(cookies: Iterable[Mapping]) -> str:
    """Write `cookies` to a Netscape-format file and return its path."""
    fd, path = tempfile.mkstemp(prefix="cookies-", suffix=".txt", dir=cookie_dir())
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write("# Netscape HTTP Cookie File\n")
            fh.write("# Generated by video-dl. Do not edit.\n\n")
            for c in cookies:
                domain = c.get("domain") or ""
                if not domain:
                    continue
                # A leading dot means "and all subdomains". Chrome reports this
                # via hostOnly=False, which is the inverse of the flag column.
                include_subdomains = "FALSE" if c.get("hostOnly") else "TRUE"
                if include_subdomains == "TRUE" and not domain.startswith("."):
                    domain = "." + domain
                path_ = c.get("path") or "/"
                secure = "TRUE" if c.get("secure") else "FALSE"
                # Session cookies have no expirationDate; 0 means "session".
                expiry = int(c.get("expirationDate") or 0)
                name = c.get("name") or ""
                value = c.get("value") or ""
                fh.write(
                    "\t".join(
                        [domain, include_subdomains, path_, secure, str(expiry), name, value]
                    )
                    + "\n"
                )
        os.chmod(path, 0o600)
        return path
    except Exception:
        try:
            os.unlink(path)
        except OSError:
            pass
        raise


def discard(path: str | None) -> None:
    """Delete a cookie file, ignoring the case where it is already gone."""
    if not path:
        return
    try:
        os.unlink(path)
    except OSError:
        pass


def sweep_orphans(*extra_dirs: str) -> list[str]:
    """Delete cookie jars left behind by a previous run. Returns what it removed.

    Called at startup. `extra_dirs` covers the old location (`downloads/`), where
    versions before this fix wrote the jars: a user upgrading may already have an
    orphan sitting there with a live session in it.
    """
    removed: list[str] = []
    directories = [cookie_dir(), *extra_dirs]
    for directory in directories:
        try:
            candidates = sorted(Path(directory).glob(COOKIE_FILE_GLOB))
        except OSError:
            continue
        for stale in candidates:
            try:
                stale.unlink()
                removed.append(str(stale))
            except OSError:
                pass
    return removed


# Cookies que el extractor de Udemy busca por nombre para armar los headers
# X-Udemy-Client-Id / X-Udemy-Authorization (ver yt_dlp/extractor/udemy.py).
UDEMY_AUTH_COOKIES = ("access_token", "client_id")


def summarize(cookies: Iterable[Mapping]) -> str:
    """Describe un set de cookies para el log, SIN exponer ningún valor.

    Solo cuenta y nombres: un valor de `access_token` en el log es tan bueno
    como la sesión misma.
    """
    cookies = list(cookies or [])
    if not cookies:
        return "sin cookies"
    names = {c.get("name") for c in cookies}
    domains = {c.get("domain") for c in cookies}
    faltantes = [n for n in UDEMY_AUTH_COOKIES if n not in names]
    estado = "ok" if not faltantes else f"FALTAN {', '.join(faltantes)}"
    return (
        f"{len(cookies)} cookies de {len(domains)} dominios "
        f"({', '.join(sorted(d for d in domains if d)[:4])}) — auth Udemy: {estado}"
    )
